CREATE OR REPLACE VIEW v_vehicle_cost_ledger AS
  SELECT account_id, vehicle_id, DATE(filled_at) AS cost_date, 'FUEL' AS cost_type, total_cost AS amount
    FROM fuel_logs
  UNION ALL
  SELECT account_id, vehicle_id, DATE(COALESCE(completed_at, opened_at)), 'MAINTENANCE', total_cost
    FROM work_orders WHERE status = 'COMPLETED'
  UNION ALL
  SELECT account_id, vehicle_id, expense_date, 'EXPENSE', amount + tax_amount
    FROM expenses WHERE vehicle_id IS NOT NULL
  UNION ALL
  SELECT account_id, vehicle_id, DATE(offence_date), 'FINE', amount
    FROM traffic_fines;

-- Full-tank to full-tank consumption (only valid between consecutive full fills)
CREATE OR REPLACE VIEW v_fuel_efficiency AS
  SELECT f.id AS fuel_log_id, f.account_id, f.vehicle_id, f.filled_at, f.quantity, f.odometer,
         f.odometer - LAG(f.odometer) OVER w AS distance_since_last_full,
         ROUND((f.odometer - LAG(f.odometer) OVER w) / NULLIF(f.quantity, 0), 2) AS km_per_unit,
         ROUND(f.quantity / NULLIF(f.odometer - LAG(f.odometer) OVER w, 0) * 100, 2) AS units_per_100km
    FROM fuel_logs f
   WHERE f.is_full_tank = 1 AND f.odometer IS NOT NULL
  WINDOW w AS (PARTITION BY f.vehicle_id ORDER BY f.odometer);

CREATE OR REPLACE VIEW v_upcoming_expiries AS
  SELECT account_id, 'VEHICLE_DOCUMENT' AS item_type, vehicle_id, NULL AS driver_id,
         doc_type AS label, expiry_date, DATEDIFF(expiry_date, CURDATE()) AS days_left
    FROM vehicle_documents
   WHERE expiry_date IS NOT NULL AND expiry_date <= DATE_ADD(CURDATE(), INTERVAL 60 DAY)
  UNION ALL
  SELECT account_id, 'INSURANCE', vehicle_id, NULL, provider_name, end_date, DATEDIFF(end_date, CURDATE())
    FROM insurance_policies
   WHERE status = 'ACTIVE' AND end_date <= DATE_ADD(CURDATE(), INTERVAL 60 DAY)
  UNION ALL
  SELECT account_id, 'DRIVER_LICENSE', NULL, id, CONCAT(first_name, ' ', COALESCE(last_name, '')),
         license_expiry_date, DATEDIFF(license_expiry_date, CURDATE())
    FROM drivers
   WHERE license_expiry_date IS NOT NULL AND status <> 'TERMINATED'
     AND license_expiry_date <= DATE_ADD(CURDATE(), INTERVAL 60 DAY);

