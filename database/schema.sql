  CONSTRAINT fk_vda_vehicle FOREIGN KEY (vehicle_id, account_id) REFERENCES vehicles(id, account_id) ON DELETE CASCADE,
  CONSTRAINT fk_vda_driver  FOREIGN KEY (driver_id, account_id)  REFERENCES drivers(id, account_id)  ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE odometer_readings (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id  BIGINT UNSIGNED NOT NULL,
  vehicle_id  BIGINT UNSIGNED NOT NULL,
  reading     DECIMAL(10,1) NOT NULL,
  read_at     DATETIME NOT NULL,
