-- =====================================================================
--  FleetOps Platform  |  Relational Schema  v1.0
--  Target : MySQL 8.0.16+ (InnoDB, utf8mb4)   -- needs CHECK + window functions
--  Tenancy: every business table carries account_id.
--           account_type = INDIVIDUAL -> a vehicle owner with 1..n vehicles
--                          BUSINESS   -> a business owner running an organization
--                                        with many vehicles, drivers, staff,
--                                        branches and departments
--  Usage  : select your IVEN database in Workbench (or add USE <db>;) and run.
--  Notes  : * public_id (UUID) is generated by the application layer.
--           * Money = DECIMAL(14,2). Times are stored in UTC.
--           * Composite FKs (x_id, account_id) stop cross-tenant data leaks.
-- =====================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =====================================================================
-- 1. TENANCY, PLANS, IDENTITY & ACCESS CONTROL
-- =====================================================================

CREATE TABLE plans (
  id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code            VARCHAR(40)  NOT NULL UNIQUE,
  name            VARCHAR(100) NOT NULL,
  target_type     ENUM('INDIVIDUAL','BUSINESS') NOT NULL,
  max_vehicles    INT UNSIGNED NULL COMMENT 'NULL = unlimited',
  max_members     INT UNSIGNED NULL,
  max_drivers     INT UNSIGNED NULL,
  features        JSON NULL,
  price_monthly   DECIMAL(10,2) NOT NULL DEFAULT 0,
  currency_code   CHAR(3) NOT NULL DEFAULT 'LKR',
  is_active       TINYINT(1) NOT NULL DEFAULT 1,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE accounts (
  id               BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_id        CHAR(36) NOT NULL UNIQUE,
  account_type     ENUM('INDIVIDUAL','BUSINESS') NOT NULL,
  name             VARCHAR(150) NOT NULL,
  legal_name       VARCHAR(200) NULL,
  registration_no  VARCHAR(60)  NULL,
  tax_no           VARCHAR(60)  NULL,
  industry         VARCHAR(100) NULL,
  email            VARCHAR(190) NULL,
  phone            VARCHAR(30)  NULL,
  website          VARCHAR(190) NULL,
  address_line1    VARCHAR(190) NULL,
  address_line2    VARCHAR(190) NULL,
  city             VARCHAR(100) NULL,
  state_province   VARCHAR(100) NULL,
  postal_code      VARCHAR(20)  NULL,
  country_code     CHAR(2) NOT NULL DEFAULT 'LK',
  timezone         VARCHAR(64) NOT NULL DEFAULT 'Asia/Colombo',
  currency_code    CHAR(3) NOT NULL DEFAULT 'LKR',
  distance_unit    ENUM('KM','MI') NOT NULL DEFAULT 'KM',
  volume_unit      ENUM('L','GAL_US','GAL_UK') NOT NULL DEFAULT 'L',
  logo_file_id     BIGINT UNSIGNED NULL,
  owner_user_id    BIGINT UNSIGNED NULL,
  status           ENUM('ACTIVE','SUSPENDED','CLOSED') NOT NULL DEFAULT 'ACTIVE',
  created_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at       DATETIME NULL,
  KEY idx_accounts_type_status (account_type, status),
  CONSTRAINT fk_accounts_owner FOREIGN KEY (owner_user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE subscriptions (
  id             BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id     BIGINT UNSIGNED NOT NULL,
  plan_id        INT UNSIGNED NOT NULL,
  status         ENUM('TRIAL','ACTIVE','PAST_DUE','CANCELLED','EXPIRED') NOT NULL DEFAULT 'TRIAL',
  billing_cycle  ENUM('MONTHLY','YEARLY') NOT NULL DEFAULT 'MONTHLY',
  trial_ends_at  DATETIME NULL,
  starts_at      DATETIME NOT NULL,
  ends_at        DATETIME NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_sub_account (account_id, status),
  CONSTRAINT fk_sub_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT fk_sub_plan    FOREIGN KEY (plan_id)    REFERENCES plans(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- A user is a global identity; one user can belong to many accounts
-- (e.g. a personal account + the employer's account).
CREATE TABLE users (
  id                 BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_id          CHAR(36) NOT NULL UNIQUE,
  email              VARCHAR(190) NOT NULL UNIQUE,
  phone              VARCHAR(30)  NULL,
  password_hash      VARCHAR(255) NOT NULL,
  first_name         VARCHAR(80)  NOT NULL,
  last_name          VARCHAR(80)  NULL,
  avatar_file_id     BIGINT UNSIGNED NULL,
  locale             VARCHAR(10) NOT NULL DEFAULT 'en',
  timezone           VARCHAR(64) NOT NULL DEFAULT 'Asia/Colombo',
  status             ENUM('PENDING','ACTIVE','LOCKED','DISABLED') NOT NULL DEFAULT 'PENDING',
  email_verified_at  DATETIME NULL,
  phone_verified_at  DATETIME NULL,
  mfa_enabled        TINYINT(1) NOT NULL DEFAULT 0,
  mfa_secret         VARCHAR(255) NULL,
  failed_login_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  locked_until       DATETIME NULL,
  last_login_at      DATETIME NULL,
  default_account_id BIGINT UNSIGNED NULL,
  created_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at         DATETIME NULL,
  CONSTRAINT fk_users_default_account FOREIGN KEY (default_account_id) REFERENCES accounts(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE roles (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id  BIGINT UNSIGNED NULL COMMENT 'NULL = system role available to all accounts',
  code        VARCHAR(40)  NOT NULL,
  name        VARCHAR(100) NOT NULL,
  description VARCHAR(255) NULL,
  is_system   TINYINT(1) NOT NULL DEFAULT 0,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_roles_account_code (account_id, code),
  CONSTRAINT fk_roles_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE permissions (
  id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code        VARCHAR(60) NOT NULL UNIQUE,   -- e.g. vehicles.manage
  module      VARCHAR(40) NOT NULL,
  description VARCHAR(255) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE role_permissions (
  role_id       INT UNSIGNED NOT NULL,
  permission_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role FOREIGN KEY (role_id)       REFERENCES roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE account_members (
  id            BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id    BIGINT UNSIGNED NOT NULL,
  user_id       BIGINT UNSIGNED NOT NULL,
  role_id       INT UNSIGNED NOT NULL,
  department_id BIGINT UNSIGNED NULL,
  location_id   BIGINT UNSIGNED NULL,
  job_title     VARCHAR(100) NULL,
  status        ENUM('ACTIVE','SUSPENDED','REMOVED') NOT NULL DEFAULT 'ACTIVE',
  joined_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_member (account_id, user_id),
  UNIQUE KEY uq_member_id_account (id, account_id),
  KEY idx_member_user (user_id),
  CONSTRAINT fk_mem_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT fk_mem_user    FOREIGN KEY (user_id)    REFERENCES users(id)    ON DELETE CASCADE,
  CONSTRAINT fk_mem_role    FOREIGN KEY (role_id)    REFERENCES roles(id),
  CONSTRAINT fk_mem_dept    FOREIGN KEY (department_id, account_id) REFERENCES departments(id, account_id),
  CONSTRAINT fk_mem_loc     FOREIGN KEY (location_id, account_id)   REFERENCES locations(id, account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invitations (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id  BIGINT UNSIGNED NOT NULL,
  email       VARCHAR(190) NOT NULL,
  role_id     INT UNSIGNED NOT NULL,
  token_hash  CHAR(64) NOT NULL UNIQUE,
  invited_by  BIGINT UNSIGNED NOT NULL,
  status      ENUM('PENDING','ACCEPTED','EXPIRED','REVOKED') NOT NULL DEFAULT 'PENDING',
  expires_at  DATETIME NOT NULL,
  accepted_at DATETIME NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_inv_account (account_id, status),
  CONSTRAINT fk_inv_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT fk_inv_role    FOREIGN KEY (role_id)    REFERENCES roles(id),
  CONSTRAINT fk_inv_by      FOREIGN KEY (invited_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE user_tokens (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id     BIGINT UNSIGNED NOT NULL,
  token_type  ENUM('REFRESH','PASSWORD_RESET','EMAIL_VERIFY','PHONE_VERIFY') NOT NULL,
  token_hash  CHAR(64) NOT NULL UNIQUE,
  user_agent  VARCHAR(255) NULL,
  ip_address  VARCHAR(45)  NULL,
  expires_at  DATETIME NOT NULL,
  used_at     DATETIME NULL,
  revoked_at  DATETIME NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_tok_user (user_id, token_type),
  CONSTRAINT fk_tok_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE account_settings (
  id            BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id    BIGINT UNSIGNED NOT NULL,
  setting_key   VARCHAR(100) NOT NULL,
  setting_value JSON NULL,
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_setting (account_id, setting_key),
  CONSTRAINT fk_set_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE audit_logs (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id  BIGINT UNSIGNED NULL,
  user_id     BIGINT UNSIGNED NULL,
  action      VARCHAR(60)  NOT NULL,           -- CREATE / UPDATE / DELETE / LOGIN ...
  entity_type VARCHAR(60)  NOT NULL,
  entity_id   BIGINT UNSIGNED NULL,
  old_values  JSON NULL,
  new_values  JSON NULL,
  ip_address  VARCHAR(45)  NULL,
  user_agent  VARCHAR(255) NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_audit_account_time (account_id, created_at),
  KEY idx_audit_entity (entity_type, entity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

