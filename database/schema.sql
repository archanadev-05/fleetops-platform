CREATE TABLE vehicles (
  id                   BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_id            CHAR(36) NOT NULL UNIQUE,
  account_id           BIGINT UNSIGNED NOT NULL,
  registration_no      VARCHAR(30) NOT NULL,
  nickname             VARCHAR(80) NULL,
  vin                  VARCHAR(25) NULL,
  engine_no            VARCHAR(40) NULL,
  chassis_no           VARCHAR(40) NULL,
  make_id              INT UNSIGNED NULL,
  model_id             INT UNSIGNED NULL,
  custom_make          VARCHAR(80)  NULL,
  custom_model         VARCHAR(100) NULL,
  year_manufactured    SMALLINT UNSIGNED NULL,
  color                VARCHAR(40) NULL,
  vehicle_type         ENUM('CAR','SUV','VAN','PICKUP','MOTORCYCLE','SCOOTER','THREE_WHEELER',
                            'BUS','TRUCK','LORRY','TRAILER','HEAVY_EQUIPMENT','OTHER') NOT NULL DEFAULT 'CAR',
  ownership_type       ENUM('OWNED','FINANCED','LEASED','RENTED','EMPLOYEE_OWNED') NOT NULL DEFAULT 'OWNED',
  usage_type           ENUM('PERSONAL','BUSINESS','MIXED') NOT NULL DEFAULT 'PERSONAL',
  fuel_type            ENUM('PETROL','DIESEL','HYBRID','PLUG_IN_HYBRID','ELECTRIC','LPG','CNG','OTHER') NOT NULL DEFAULT 'PETROL',
  transmission         ENUM('MANUAL','AUTOMATIC','CVT','OTHER') NULL,
  engine_cc            INT UNSIGNED NULL,
  seating_capacity     TINYINT UNSIGNED NULL,
  payload_kg           INT UNSIGNED NULL,
  tank_capacity_l      DECIMAL(6,2) NULL,
  battery_capacity_kwh DECIMAL(6,2) NULL,
  purchase_date        DATE NULL,
  purchase_price       DECIMAL(14,2) NULL,
  purchase_odometer    DECIMAL(10,1) NULL,
  current_odometer     DECIMAL(10,1) NOT NULL DEFAULT 0,
  odometer_updated_at  DATETIME NULL,
  location_id          BIGINT UNSIGNED NULL COMMENT 'home depot / garage',
  department_id        BIGINT UNSIGNED NULL,
  primary_driver_id    BIGINT UNSIGNED NULL,
  photo_file_id        BIGINT UNSIGNED NULL,
  status               ENUM('ACTIVE','IN_SERVICE','INACTIVE','SOLD','SCRAPPED','STOLEN') NOT NULL DEFAULT 'ACTIVE',
  sold_date            DATE NULL,
  sold_price           DECIMAL(14,2) NULL,
  notes                TEXT NULL,
  created_at           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at           DATETIME NULL,
  UNIQUE KEY uq_veh_id_account (id, account_id),
  UNIQUE KEY uq_veh_reg (account_id, registration_no),
  KEY idx_veh_status (account_id, status),
  KEY idx_veh_vin (vin),
  CONSTRAINT chk_veh_year CHECK (year_manufactured IS NULL OR year_manufactured BETWEEN 1900 AND 2100),
  CONSTRAINT chk_veh_odo  CHECK (current_odometer >= 0),
  CONSTRAINT fk_veh_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE CASCADE,
  CONSTRAINT fk_veh_make    FOREIGN KEY (make_id)  REFERENCES vehicle_makes(id),
  CONSTRAINT fk_veh_model   FOREIGN KEY (model_id) REFERENCES vehicle_models(id),
  CONSTRAINT fk_veh_loc     FOREIGN KEY (location_id, account_id)       REFERENCES locations(id, account_id),
  CONSTRAINT fk_veh_dept    FOREIGN KEY (department_id, account_id)     REFERENCES departments(id, account_id),
  CONSTRAINT fk_veh_driver  FOREIGN KEY (primary_driver_id, account_id) REFERENCES drivers(id, account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE vehicle_driver_assignments (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id      BIGINT UNSIGNED NOT NULL,
  vehicle_id      BIGINT UNSIGNED NOT NULL,
  driver_id       BIGINT UNSIGNED NOT NULL,
  assignment_type ENUM('PRIMARY','TEMPORARY','POOL') NOT NULL DEFAULT 'PRIMARY',
  starts_at       DATETIME NOT NULL,
  ends_at         DATETIME NULL,
  notes           VARCHAR(255) NULL,
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_vda_vehicle (vehicle_id, starts_at),
  KEY idx_vda_driver  (driver_id, starts_at),
