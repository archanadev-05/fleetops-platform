-- 14. TRIGGER: keep vehicles.current_odometer in sync
-- =====================================================================

DELIMITER $$
CREATE TRIGGER trg_odometer_after_insert
AFTER INSERT ON odometer_readings
FOR EACH ROW
BEGIN
  UPDATE vehicles
     SET current_odometer = NEW.reading,
         odometer_updated_at = NEW.read_at
   WHERE id = NEW.vehicle_id
     AND account_id = NEW.account_id
     AND NEW.reading >= current_odometer;
END$$
DELIMITER ;

