-- Generic attachment link (receipts, photos, PDFs) to any entity.
-- Polymorphic by design, so integrity on entity_id is enforced by the app.
CREATE TABLE attachments (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  account_id  BIGINT UNSIGNED NOT NULL,
  file_id     BIGINT UNSIGNED NOT NULL,
  entity_type VARCHAR(50) NOT NULL,           -- vehicle, driver, work_order, incident ...
  entity_id   BIGINT UNSIGNED NOT NULL,
  label       VARCHAR(120) NULL,
